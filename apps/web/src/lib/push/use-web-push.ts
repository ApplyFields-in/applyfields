'use client';

import { useEffect, useState, useTransition } from 'react';
import { API_URL, apiDelete, apiGet, apiPost } from '@/lib/api';
import type { PushPublicKeyResponse, PushSubscriptionInput } from '@applyfields/types';

function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/');
  const rawData = window.atob(base64);
  const outputArray = new Uint8Array(rawData.length);
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

export function useWebPush() {
  const [isSupported, setIsSupported] = useState(false);
  const [permission, setPermission] = useState<NotificationPermission>('default');
  const [isSubscribed, setIsSubscribed] = useState(false);
  const [isLoading, setIsLoading] = useState(true);
  const [isPending, startTransition] = useTransition();

  useEffect(() => {
    if (typeof window === 'undefined') return;

    const supported = 'serviceWorker' in navigator && 'PushManager' in window && 'Notification' in window;
    setIsSupported(supported);

    if (!supported) {
      setIsLoading(false);
      return;
    }

    setPermission(Notification.permission);

    // Check existing registration and subscription
    navigator.serviceWorker.ready
      .then((reg) => reg.pushManager.getSubscription())
      .then((sub) => {
        setIsSubscribed(Boolean(sub));
      })
      .catch((err) => {
        console.warn('[useWebPush] Check subscription failed:', err);
      })
      .finally(() => {
        setIsLoading(false);
      });
  }, []);

  async function subscribe(): Promise<{ ok: boolean; error?: string }> {
    if (!isSupported) {
      return { ok: false, error: 'Push notifications are not supported on this browser' };
    }

    try {
      setIsLoading(true);

      // 1. Request browser permission
      const perm = await Notification.requestPermission();
      setPermission(perm);
      if (perm !== 'granted') {
        setIsLoading(false);
        return { ok: false, error: 'Notification permission was denied' };
      }

      // 2. Register service worker if not already registered
      let reg = await navigator.serviceWorker.getRegistration();
      if (!reg) {
        reg = await navigator.serviceWorker.register('/sw.js');
      }
      await navigator.serviceWorker.ready;

      // 3. Fetch VAPID public key from backend
      const keyRes = await apiGet<PushPublicKeyResponse>('/notifications/push-public-key');
      if (!keyRes || !keyRes.publicKey) {
        throw new Error('Failed to retrieve VAPID public key from server');
      }

      // 4. Subscribe via browser PushManager
      const convertedKey = urlBase64ToUint8Array(keyRes.publicKey);
      const sub = await reg.pushManager.subscribe({
        userVisibleOnly: true,
        applicationServerKey: convertedKey as unknown as BufferSource,
      });

      const subJson = sub.toJSON();
      if (!subJson.endpoint || !subJson.keys?.p256dh || !subJson.keys?.auth) {
        throw new Error('Invalid subscription keys generated by browser');
      }

      const input: PushSubscriptionInput = {
        endpoint: subJson.endpoint,
        keys: {
          p256dh: subJson.keys.p256dh,
          auth: subJson.keys.auth,
        },
        user_agent: navigator.userAgent,
      };

      // 5. Send subscription to ApplyFields API
      const saveRes = await apiPost('/notifications/push-subscribe', input);
      if (saveRes.status >= 400) {
        throw new Error('Server failed to record push subscription');
      }

      setIsSubscribed(true);
      window.dispatchEvent(new CustomEvent('push-subscription-changed', { detail: { isSubscribed: true } }));
      return { ok: true };
    } catch (err: unknown) {
      const msg = (err as Error).message || 'Failed to enable push notifications';
      console.error('[useWebPush] Subscribe error:', err);
      return { ok: false, error: msg };
    } finally {
      setIsLoading(false);
    }
  }

  async function unsubscribe(): Promise<{ ok: boolean; error?: string }> {
    if (!isSupported) return { ok: false };

    try {
      setIsLoading(true);
      const reg = await navigator.serviceWorker.ready;
      const sub = await reg.pushManager.getSubscription();

      if (sub) {
        const endpoint = sub.endpoint;
        await sub.unsubscribe();
        await apiPost('/notifications/push-unsubscribe', { endpoint }).catch(() => null);
      }

      setIsSubscribed(false);
      window.dispatchEvent(new CustomEvent('push-subscription-changed', { detail: { isSubscribed: false } }));
      return { ok: true };
    } catch (err: unknown) {
      console.error('[useWebPush] Unsubscribe error:', err);
      return { ok: false, error: (err as Error).message };
    } finally {
      setIsLoading(false);
    }
  }

  return {
    isSupported,
    permission,
    isSubscribed,
    isLoading: isLoading || isPending,
    subscribe,
    unsubscribe,
  };
}
