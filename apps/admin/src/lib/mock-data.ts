export function getMockAdminUsers(params: { q?: string; type?: string; page?: number } = {}): AdminUserList {
  let list = [...MOCK_ADMIN_USERS];

  if (params.type === 'staff') {
    list = list.filter((u) => u.roles && u.roles.length > 0);
  } else if (params.type === 'citizens') {
    list = list.filter((u) => !u.roles || u.roles.length === 0);
  }

  if (params.q) {
    const qLower = params.q.toLowerCase();
    list = list.filter(
      (u) =>
        (u.full_name && u.full_name.toLowerCase().includes(qLower)) ||
        (u.email && u.email.toLowerCase().includes(qLower)) ||
        (u.phone && u.phone.toLowerCase().includes(qLower)),
    );
  }

  const staffCount = MOCK_ADMIN_USERS.filter((u) => u.roles && u.roles.length > 0).length;
  const citizenCount = MOCK_ADMIN_USERS.filter((u) => !u.roles || u.roles.length === 0).length;

  return {
    users: list,
    total: list.length,
    staff_count: staffCount,
    citizen_count: citizenCount,
    page: params.page || 1,
    limit: 20,
  };
}

